cli_codex_workflow_mcp_env_vars_json() {
    local pair name entry first=true
    local -a names=()
    local -A seen=()

    while IFS= read -r pair; do
        [[ -n "$pair" ]] || continue
        name="${pair%%=*}"
        [[ "$name" =~ ^[A-Za-z_][A-Za-z0-9_]*$ ]] || continue
        [[ -z "${seen[$name]:-}" ]] || continue
        seen[$name]=1
        names+=("$name")
    done < <(ar_runtime_env_pairs)

    for name in \
        "${STORAGE_NAMES[@]}" \
        UV_LINK_MODE \
        GIT_SSH_COMMAND \
        SSH_AUTH_SOCK \
        https_proxy \
        http_proxy \
        HTTPS_PROXY \
        HTTP_PROXY \
        NO_PROXY \
        no_proxy
    do
        [[ "$name" =~ ^[A-Za-z_][A-Za-z0-9_]*$ ]] || continue
        [[ -z "${seen[$name]:-}" ]] || continue
        seen[$name]=1
        names+=("$name")
    done

    if [[ -n "${AR_EXTRA_ENV:-}" ]]; then
        local IFS='|'
        for entry in $AR_EXTRA_ENV; do
            name="${entry%%=*}"
            [[ "$name" =~ ^[A-Za-z_][A-Za-z0-9_]*$ ]] || continue
            [[ -z "${seen[$name]:-}" ]] || continue
            seen[$name]=1
            names+=("$name")
        done
    fi

    printf '['
    for name in "${names[@]}"; do
        if [[ "$first" == "true" ]]; then
            first=false
        else
            printf ','
        fi
        json_string "$name"
    done
    printf ']'
}

cli_codex_translate_cli_args() {
    local translated=()
    local i arg next mcp_command mcp_env_vars

    for ((i=0; i<${#CLI_ARGS[@]}; i++)); do
        arg="${CLI_ARGS[$i]}"
        case "$arg" in
            --resume)
                translated+=("resume")
                next="${CLI_ARGS[$((i+1))]:-}"
                if [[ -n "$next" && ! "$next" =~ ^- ]]; then
                    translated+=("$next")
                    i=$((i + 1))
                fi
                ;;
            --continue)
                translated+=("resume" "--last")
                ;;
            *)
                translated+=("$arg")
                ;;
        esac
    done
    CLI_ARGS=()
    if [[ "$MODEL_SPECIFIED" == "false" && -n "${AR_DEFAULT_MODEL:-}" ]]; then
        CLI_ARGS+=("--model" "$AR_DEFAULT_MODEL")
    fi
    if [[ "$YOLO_MODE" == "true" ]]; then
        CLI_ARGS+=("--dangerously-bypass-approvals-and-sandbox")
    fi
    if capability_enabled imperative-workflows; then
        mcp_command="$(client_runtime_command)"
        mcp_env_vars="$(cli_codex_workflow_mcp_env_vars_json)"
        CLI_ARGS+=(
            --config "mcp_servers.agentic_workflows.command=$(json_string "$mcp_command")"
            --config 'mcp_servers.agentic_workflows.args=["exec-workflow-mcp","--client","codex"]'
            --config "mcp_servers.agentic_workflows.env_vars=$mcp_env_vars"
            --config 'mcp_servers.agentic_workflows.required=true'
            --config 'mcp_servers.agentic_workflows.startup_timeout_sec=60'
            --config 'mcp_servers.agentic_workflows.tool_timeout_sec=3600'
            --config 'mcp_servers.agentic_workflows.enabled_tools=["start_workflow","resume_workflow","workflow_status","cancel_workflow","reset_workflow_context"]'
        )
    fi
    CLI_ARGS+=("${translated[@]}")
}

cli_codex_prepare_external_client() {
    local dispatcher="$SCRIPT_DIR/scripts/bin/agentic-team-client"

    if ! command -v codex >/dev/null 2>&1; then
        echo "Error: codex is required to register the prepared desktop/CLI integration." >&2
        return 1
    fi
    codex mcp remove agentic_workflows >/dev/null 2>&1 || true
    codex mcp add agentic_workflows -- "$dispatcher" exec-workflow-mcp --client codex

    if [[ "${CODEX_HOOK_REVIEW_REQUIRED:-false}" == "true" ]]; then
        printf '\nAgentic Team installed or changed Codex hooks. Codex requires explicit review before they can run.\n'
        printf 'After preparation completes, run: codex -C %q\n' "$WORKSPACE_DIR"
        printf 'Then enter /hooks in the Codex TUI and trust the Agentic Team hooks.\n'
        printf 'This review is normally needed only once after installation.\n\n'
    fi
}

cli_codex_cleanup_legacy_client_configuration() {
    if [[ "${CODEX_LEGACY_CLIENT_CONFIG:-false}" == "true" ]]; then
        remove_empty_json_file "$WORKSPACE_DIR/.codex/hooks.json"
    fi
    rmdir "$WORKSPACE_DIR/.codex/hooks" 2>/dev/null || true
}

