cli_codex_render_agent() {
    local source_path="$1"
    local target_path="$2"
    local agent_name="$3"
    local description="$4"
    local codex_reasoning_effort="$5"
    local temp_path="${target_path}.tmp"
    local body_path="${target_path}.body.tmp"
    local name_escaped description_escaped reasoning_escaped

    if ! render_expanded_agent_body "$source_path" > "$body_path"; then
        rm -f "$body_path"
        return 1
    fi

    name_escaped="$(printf '%s' "$agent_name" | toml_escape)"
    description_escaped="$(printf '%s' "$description" | toml_escape)"
    reasoning_escaped="$(printf '%s' "$codex_reasoning_effort" | toml_escape)"
    {
        printf 'name = "%s"\n' "$name_escaped"
        printf 'description = "%s"\n' "$description_escaped"
        if [[ -n "$reasoning_escaped" ]]; then
            printf 'model_reasoning_effort = "%s"\n' "$reasoning_escaped"
        fi
        printf 'developer_instructions = """\n'
        printf '<!-- Generated by agentic-team. Edit the source agent definition to change this agent. -->\n\n'
        sed 's/"""/\\"""/g' "$body_path"
        printf '\n'
        render_agentic_notes_for_agent_type "$agent_name" | sed 's/"""/\\"""/g'
        printf '\n"""\n'
    } > "$temp_path"
    rm -f "$body_path"
    mv "$temp_path" "$target_path"
}

cli_codex_setup_compaction_hooks() {
    local post_compact_command patch_json legacy_script
    post_compact_command="agentic-team-client hook codex-post-compact --client codex"
    if ! codex_hook_definition_exists \
        "$CODEX_STATE_DIR/hooks.json" \
        SessionStart \
        compact \
        "$post_compact_command" \
        120 \
        "Agentic Team compaction refresh"
    then
        CODEX_HOOK_REVIEW_REQUIRED=true
    fi
    patch_json=$(cat <<EOF
{
  "hooks": {
    "PostCompact": [],
    "SessionStart": [
      {
        "matcher": "compact",
        "hooks": [
          {
            "type": "command",
            "command": $(json_string "$post_compact_command"),
            "timeout": 120,
            "statusMessage": "Agentic Team compaction refresh"
          }
        ]
      }
    ],
    "UserPromptSubmit": []
  }
}
EOF
)
    if ! merge_managed_hook_json "$CODEX_STATE_DIR/hooks.json" "codex-post-compact" "$patch_json"; then
        echo "Warning: Could not update Codex compaction hook settings."
    fi

    legacy_script="$WORKSPACE_DIR/.codex/hooks/agentic-team-compaction.py"
    if [[ -f "$legacy_script" ]] && grep -q "Generated by agentic-team" "$legacy_script"; then
        rm -f "$legacy_script"
    fi
    if [[ -f "$WORKSPACE_DIR/.codex/hooks.json" ]] && grep -Eq 'agentic-team|imperative-workflows' "$WORKSPACE_DIR/.codex/hooks.json"; then
        CODEX_LEGACY_CLIENT_CONFIG=true
        merge_managed_hook_json "$WORKSPACE_DIR/.codex/hooks.json" "agentic-team-compaction" '{"hooks":{"PostCompact":[],"UserPromptSubmit":[],"SessionStart":[]}}'
    fi
}

