render_gemini_compaction_hook_script() {
    local target_path="$1"
    local managed_marker="Generated by agentic-team"

    if [[ -f "$target_path" ]] && ! grep -q "$managed_marker" "$target_path"; then
        echo "Warning: Skipping existing Gemini compaction hook script at $target_path (not managed by agentic-team)"
        return 1
    fi

    mkdir -p "$(dirname "$target_path")"
    cat > "$target_path" <<'PY'
#!/usr/bin/env python3
# Generated by agentic-team. Edit the launcher to change this file.
import json
import subprocess
import sys
import time
from pathlib import Path


def run_command(command: list[str]) -> tuple[bool, str]:
    try:
        result = subprocess.run(command, text=True, capture_output=True, timeout=60)
    except Exception as exc:
        return False, f"{command[0]} did not run: {exc}"
    output = (result.stdout or result.stderr or "").strip()
    if result.returncode == 0:
        return True, output
    return False, output or f"{command[0]} exited with status {result.returncode}."


def run_refresh(capability_refresh_cli: str, instruction_path: str, project_dir: str, agent_type: str, cli: str) -> tuple[bool, str]:
    if not capability_refresh_cli:
        return False, "capability-refresh was not configured."
    command = [
        capability_refresh_cli,
        "--instruction-path",
        instruction_path,
        "--project-dir",
        project_dir,
        "--agent-type",
        agent_type,
        "--cli",
        cli,
    ]
    return run_command(command)


def refresh_message(instruction_path: str, capability_refresh_cli: str, project_dir: str, agent_type: str, cli: str) -> str:
    refreshed, refresh_status = run_refresh(capability_refresh_cli, instruction_path, project_dir, agent_type, cli)
    refresh_sentence = (
        "Agentic Team just refreshed configured capabilities and rematerialized the rendered instruction file."
        if refreshed
        else f"Agentic Team tried to refresh configured capabilities, but refresh failed: {refresh_status}"
    )
    return (
        "You have just experienced context compaction. Treat this moment as "
        "the new `since the last compaction` boundary for Agentic Notes. "
        f"{refresh_sentence} Before continuing, read "
        f"`{instruction_path}`, the instruction file rendered for this "
        "specific Agentic Team invocation, then continue with whatever "
        "task was in progress before compaction. Do not restart from scratch."
    )


def marker_path() -> Path:
    return Path(__file__).with_name(".agentic-team-compaction.pending")


def mark_pending(instruction_path: str) -> None:
    try:
        json.load(sys.stdin)
    except Exception:
        pass
    marker_path().write_text(
        json.dumps({"instruction_path": instruction_path, "time": time.time()}) + "\n",
        encoding="utf-8",
    )
    print(json.dumps({
        "systemMessage": "Agentic Team will refresh instructions on the next model call.",
        "suppressOutput": True,
    }))


def inject_pending(default_instruction_path: str, capability_refresh_cli: str, project_dir: str, agent_type: str, cli: str) -> None:
    try:
        hook_input = json.load(sys.stdin)
    except Exception:
        hook_input = {}

    marker = marker_path()
    if not marker.exists():
        print("{}")
        return

    try:
        marker_data = json.loads(marker.read_text(encoding="utf-8"))
    except Exception:
        marker_data = {}
    try:
        marker.unlink()
    except FileNotFoundError:
        pass

    instruction_path = marker_data.get("instruction_path") or default_instruction_path
    llm_request = hook_input.get("llm_request")
    if not isinstance(llm_request, dict):
        print("{}")
        return

    messages = llm_request.get("messages")
    if not isinstance(messages, list):
        messages = []

    updated_request = dict(llm_request)
    updated_request["messages"] = messages + [{
        "role": "system",
        "content": refresh_message(str(instruction_path), capability_refresh_cli, project_dir, agent_type, cli),
    }]
    print(json.dumps({
        "hookSpecificOutput": {
            "hookEventName": "BeforeModel",
            "llm_request": updated_request,
        },
        "suppressOutput": True,
    }))


def main() -> None:
    mode = sys.argv[1] if len(sys.argv) > 1 else "mark"
    instruction_path = sys.argv[2] if len(sys.argv) > 2 else "GEMINI.md"
    capability_refresh_cli = sys.argv[3] if len(sys.argv) > 3 else ""
    project_dir = sys.argv[4] if len(sys.argv) > 4 else "."
    agent_type = sys.argv[5] if len(sys.argv) > 5 else "research-coordinator"
    cli = sys.argv[6] if len(sys.argv) > 6 else "gemini"
    if mode == "inject":
        inject_pending(instruction_path, capability_refresh_cli, project_dir, agent_type, cli)
    else:
        mark_pending(instruction_path)


if __name__ == "__main__":
    main()
PY
    chmod +x "$target_path"
}

cli_gemini_setup_compaction_hooks() {
    local script_path="$WORKSPACE_DIR/.gemini/hooks/agentic-team-compaction.py"
    render_gemini_compaction_hook_script "$script_path" || return 0

    local script_runtime instruction_runtime capability_refresh_runtime project_runtime agent_type_runtime cli_runtime python_runtime mark_command inject_command patch_json
    script_runtime="$(workspace_runtime_path ".gemini/hooks/agentic-team-compaction.py")"
    instruction_runtime="$(workspace_runtime_path "$INSTRUCTION_TARGET")"
    capability_refresh_runtime="$(ar_core_bin_env_path)/capability-refresh"
    project_runtime="$(workspace_root_runtime_path)"
    agent_type_runtime="$AR_MAIN_AGENT"
    cli_runtime="$AR_CLI"
    python_runtime="$(python_runtime_command_string)"
    mark_command="$python_runtime $(shell_quote "$script_runtime") mark $(shell_quote "$instruction_runtime") $(shell_quote "$capability_refresh_runtime") $(shell_quote "$project_runtime") $(shell_quote "$agent_type_runtime") $(shell_quote "$cli_runtime")"
    inject_command="$python_runtime $(shell_quote "$script_runtime") inject $(shell_quote "$instruction_runtime") $(shell_quote "$capability_refresh_runtime") $(shell_quote "$project_runtime") $(shell_quote "$agent_type_runtime") $(shell_quote "$cli_runtime")"
    patch_json=$(cat <<EOF
{
  "hooks": {
    "PreCompress": [
      {
        "hooks": [
          {
            "type": "command",
            "command": $(json_string "$mark_command"),
            "name": "Agentic Team compaction marker",
            "description": "Marks a compression so the next model request refreshes the rendered instruction file.",
            "timeout": 10000
          }
        ]
      }
    ],
    "BeforeModel": [
      {
        "hooks": [
          {
            "type": "command",
            "command": $(json_string "$inject_command"),
            "name": "Agentic Team compaction refresh",
            "description": "After compression, asks the model to read the invocation-specific instruction file and resume work.",
            "timeout": 120000
          }
        ]
      }
    ]
  }
}
EOF
)
    if ! merge_managed_hook_json "$WORKSPACE_DIR/.gemini/settings.json" "agentic-team-compaction" "$patch_json"; then
        echo "Warning: Could not update Gemini compaction hook settings."
    fi
}

cli_gemini_setup_steering_hooks() {
    local script_path="$WORKSPACE_DIR/.gemini/hooks/agentic-team-steering.py"
    render_steering_context_hook_script "$script_path" || return 0

    local script_runtime agentic_notes_runtime project_runtime agent_type_runtime python_runtime command patch_json
    script_runtime="$(workspace_runtime_path ".gemini/hooks/agentic-team-steering.py")"
    agentic_notes_runtime="$(agentic_notes_runtime_command)" || return 0
    project_runtime="$(workspace_root_runtime_path)"
    agent_type_runtime="$AR_MAIN_AGENT"
    python_runtime="$(python_runtime_command_string)"
    command="$python_runtime $(shell_quote "$script_runtime") gemini-before-model $(shell_quote "$agentic_notes_runtime") $(shell_quote "$project_runtime") $(shell_quote "$agent_type_runtime")"
    patch_json=$(cat <<EOF
{
  "hooks": {
    "BeforeModel": [
      {
        "hooks": [
          {
            "type": "command",
            "command": $(json_string "$command"),
            "name": "Agentic Notes steering",
            "description": "Injects changed Agentic Notes topics before the next model request.",
            "timeout": 15000
          }
        ]
      }
    ]
  }
}
EOF
)
    if ! merge_managed_hook_json "$WORKSPACE_DIR/.gemini/settings.json" "agentic-team-steering" "$patch_json"; then
        echo "Warning: Could not update Gemini steering hook settings."
    fi
}

cli_gemini_setup_tool_transport() {
    local workflow_mcp_command patch_json workflow_server
    if workflow_mcp_command="$(imperative_workflows_mcp_runtime_command)"; then
        workflow_server=$(cat <<EOF
{
  "command": $(json_string "$workflow_mcp_command"),
  "timeout": 3600000,
  "trust": false
}
EOF
)
    else
        workflow_server=null
    fi
    patch_json=$(cat <<EOF
{"mcpServers":{"agentic_tools":null,"agentic_workflows":$workflow_server}}
EOF
)
    merge_managed_hook_json \
        "$WORKSPACE_DIR/.gemini/settings.json" \
        "agentic-team-tools" \
        "$patch_json"
}

cli_gemini_translate_cli_args() {
    if [[ "$MODEL_SPECIFIED" == "false" && -n "${AR_DEFAULT_MODEL:-}" ]]; then
        CLI_ARGS+=("--model" "$AR_DEFAULT_MODEL")
    fi
    if [[ " ${CLI_ARGS[*]} " != *" --sandbox "* ]]; then
        CLI_ARGS+=("--sandbox=false")
    fi
    if [[ "$DEBUG_LAUNCH" == "true" ]]; then
        CLI_ARGS+=("--debug")
    fi
    if [[ "$YOLO_MODE" == "true" ]]; then
        CLI_ARGS+=("--yolo")
    fi
}

cli_gemini_add_env_args() {
