enabled_provider_names() {
    local raw="${AR_INSTRUCTION_PROVIDERS:-agentic-notes,experiment-log}"
    local provider

    raw="${raw//,/ }"
    for provider in $raw; do
        [[ -n "$provider" ]] || continue
        [[ "$provider" == "none" ]] && continue
        if [[ "$provider" =~ ^[A-Za-z0-9._-]+$ ]]; then
            printf '%s\n' "$provider"
        else
            echo "Warning: Ignoring invalid instruction provider name: $provider" >&2
        fi
    done
}

provider_enabled() {
    local needle="$1"
    local provider

    for provider in $(enabled_provider_names); do
        [[ "$provider" == "$needle" ]] && return 0
    done
    return 1
}

provider_path() {
    local provider_name="$1"
    local candidate

    for candidate in \
        "$STATE_ROOT/repos/org-agentic-notes/providers/$provider_name/bin/$provider_name" \
        "$STATE_ROOT/repos/org-agentic-notes/providers/$provider_name/$provider_name" \
        "$SCRIPT_DIR/scripts/providers/$provider_name"
    do
        if [[ -x "$candidate" ]]; then
            printf '%s\n' "$candidate"
            return 0
        fi
    done

    return 1
}

provider_call() {
    local provider_name="$1"
    shift
    local provider_exe

    if ! provider_exe="$(provider_path "$provider_name")"; then
        echo "Warning: Instruction provider not found: $provider_name" >&2
        return 127
    fi
    "$provider_exe" "$@"
}

