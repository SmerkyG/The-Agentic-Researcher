PROVIDER_SECTION_DIR=""

render_agentic_notes_for_agent_type() {
    local render_agent_type="$1"
    local rendered_path

    provider_enabled agentic-notes || return 0

    if [[ -n "$PROVIDER_SECTION_DIR" ]]; then
        rendered_path="$PROVIDER_SECTION_DIR/$render_agent_type.md"
        if [[ -f "$rendered_path" ]]; then
            cat "$rendered_path"
            return 0
        fi
    fi
    provider_call agentic-notes render-section \
        --project-dir "$WORKSPACE_DIR" \
        --agent-type "$render_agent_type" 2>/dev/null || true
}

prepare_provider_sections() {
    [[ ${#ACTIVE_PROJECT_AGENT_NAMES[@]} -gt 0 ]] || return 0
    provider_enabled agentic-notes || return 0

    local temp_root render_args agent_name
    temp_root="$STATE_ROOT/tmp"
    mkdir -p "$temp_root"
    PROVIDER_SECTION_DIR="$(mktemp -d "$temp_root/provider-sections.XXXXXX")" || {
        PROVIDER_SECTION_DIR=""
        return 0
    }

    render_args=(render-sections --project-dir "$WORKSPACE_DIR" --output-dir "$PROVIDER_SECTION_DIR")
    for agent_name in "${ACTIVE_PROJECT_AGENT_NAMES[@]}"; do
        render_args+=(--agent-type "$agent_name")
    done

    if ! provider_call agentic-notes "${render_args[@]}" >/dev/null 2>/dev/null; then
        rm -rf "$PROVIDER_SECTION_DIR"
        PROVIDER_SECTION_DIR=""
    fi
}

cleanup_provider_sections() {
    if [[ -n "$PROVIDER_SECTION_DIR" ]]; then
        rm -rf "$PROVIDER_SECTION_DIR"
        PROVIDER_SECTION_DIR=""
    fi
}

valid_agent_name() {
    [[ "$1" =~ ^[A-Za-z0-9._-]+$ ]]
}

render_markdown_agent_file() {
    local source_path="$1"
    local target_path="$2"
    local agent_name="$3"
    local temp_path="${target_path}.tmp"

    awk -v agent_name="$agent_name" '
        BEGIN { inserted=0; in_frontmatter=0 }
        NR == 1 && $0 == "---" { in_frontmatter=1; print; next }
        in_frontmatter && $0 ~ /^[[:space:]]*(kind|codex_reasoning_effort|model_reasoning_effort):[[:space:]]*/ { next }
        in_frontmatter && $0 == "---" {
            print
            print ""
            print "<!-- Generated by agentic-researcher. Edit the source agent definition to change this agent. -->"
            inserted=1
            in_frontmatter=0
            next
        }
        { print }
        END {
            if (inserted == 0) {
                print "<!-- Generated by agentic-researcher. Edit the source agent definition to change this agent. -->"
            }
        }
    ' "$source_path" | expand_modules_from_stdin > "$temp_path"
    {
        printf '\n'
        render_agentic_notes_for_agent_type "$agent_name"
    } >> "$temp_path"

    mv "$temp_path" "$target_path"
}

