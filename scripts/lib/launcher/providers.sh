setup_provider_refresh_loops() {
    [[ "$TEST_MODE" == "true" ]] && return 0
    [[ "$RENDER_ONLY" == "true" ]] && return 0

    case "${AR_NOTES_AUTO_REFRESH:-true}" in
        0|false|False|FALSE|no|No|NO|off|Off|OFF)
            return 0
            ;;
    esac

    case "${AR_NOTES_REFRESH_MODE:-periodic}" in
        periodic|background)
            ;;
        *)
            return 0
            ;;
    esac

    local interval heartbeat_period heartbeat_dir heartbeat_file refresh_log launcher_pid stale_seconds
    interval="${AR_NOTES_REFRESH_INTERVAL_SECONDS:-120}"
    if ! [[ "$interval" =~ ^[0-9]+$ ]] || [[ "$interval" -lt 1 ]]; then
        interval=120
    fi
    heartbeat_period=$((interval / 4))
    if [[ "$heartbeat_period" -lt 1 ]]; then
        heartbeat_period=1
    elif [[ "$heartbeat_period" -gt 30 ]]; then
        heartbeat_period=30
    fi
    stale_seconds=$((interval * 2))
    if [[ "$stale_seconds" -lt $((heartbeat_period * 3)) ]]; then
        stale_seconds=$((heartbeat_period * 3))
    fi

    heartbeat_dir="$STATE_ROOT/refresh-heartbeats/$AR_PROJECT_ID"
    heartbeat_file="$heartbeat_dir/$$.heartbeat"
    refresh_log="$STATE_ROOT/logs/agentic-notes-refresh-$AR_PROJECT_ID.log"
    launcher_pid="$$"
    mkdir -p "$heartbeat_dir" "$(dirname "$refresh_log")"
    touch "$heartbeat_file"

    (
        while kill -0 "$launcher_pid" 2>/dev/null; do
            touch "$heartbeat_file"
            sleep "$heartbeat_period"
        done
        rm -f "$heartbeat_file"
    ) >/dev/null 2>&1 &

    local provider_name
    for provider_name in $(enabled_provider_names); do
        provider_call "$provider_name" refresh-loop \
            --project-dir "$WORKSPACE_DIR" \
            --heartbeat-dir "$heartbeat_dir" \
            --interval-seconds "$interval" \
            --stale-seconds "$stale_seconds" \
            --agent-type "${AR_MAIN_AGENT:-research-coordinator}" \
            --tool "$AR_CLI_TOOL" >>"$refresh_log" 2>&1 &
    done
}

setup_provider_instruction_sections() {
    [[ -n "${INSTRUCTION_TARGET:-}" ]] || return 0
    local instruction_path="$WORKSPACE_DIR/$INSTRUCTION_TARGET"
    local temp_path provider_name section

    [[ -f "$instruction_path" ]] || return 0

    export AR_STATE_ROOT AR_ORG_NOTES_REPO AR_MAIN_AGENT AR_INSTRUCTION_PROVIDERS
    export AR_AGENT_BRANCH AR_AGENT_BRANCH_ID AR_AGENT_TOPIC AR_AGENT_BRANCH_PREFIX AR_BRANCH_OWNERSHIP
    export AR_USER_ID AR_PROJECT_ID AR_SESSION_ID
    export AR_AGENTIC_STATE_BRANCH AR_NOTES_AUTO_REFRESH AR_SANDBOX
    export AR_NOTES_CLI AR_TOOL_CLI AR_CLI_TOOL TEST_MODE RENDER_ONLY
    AR_NOTES_CLI="$(ar_notes_cli_host_path)"
    AR_TOOL_CLI="$(ar_tool_cli_host_path)"

    temp_path="${instruction_path}.tmp"
    cp "$instruction_path" "$temp_path"

    for provider_name in $(enabled_provider_names); do
        section="$(
            provider_call "$provider_name" render-instruction \
                --project-dir "$WORKSPACE_DIR" \
                --agent-type "${AR_MAIN_AGENT:-research-coordinator}" \
                --tool "$AR_CLI_TOOL" 2>/dev/null || true
        )"
        if [[ -n "$section" ]]; then
            {
                printf '\n'
                printf '%s\n' "$section"
            } >> "$temp_path"
        fi
    done

    mv "$temp_path" "$instruction_path"
}

