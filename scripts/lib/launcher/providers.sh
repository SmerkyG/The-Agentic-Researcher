ACTIVE_PROJECT_AGENT_NAMES=()

add_active_project_agent_name() {
    local agent_name="$1"
    ACTIVE_PROJECT_AGENT_NAMES+=("$agent_name")
}

collect_active_project_agent_names() {
    local source_dir="$1"
    local override_dir="$2"
    local source_path agent_name kind

    [[ -d "$source_dir" ]] || return 0
    for source_path in "$source_dir"/*.md; do
        [[ -f "$source_path" ]] || continue
        agent_name="$(agent_name_for_source "$source_path")"
        if [[ -n "$override_dir" ]] && agent_name_exists_in_source_dir "$agent_name" "$override_dir"; then
            continue
        fi
        [[ -n "$agent_name" ]] || continue
        valid_agent_name "$agent_name" || continue
        kind="$(agent_kind_for_source "$source_path")"
        [[ "$kind" == "subagent" ]] || continue
        add_active_project_agent_name "$agent_name"
    done
}

is_active_project_agent_name() {
    local needle="$1"
    local agent_name

    for agent_name in "${ACTIVE_PROJECT_AGENT_NAMES[@]}"; do
        [[ "$agent_name" == "$needle" ]] && return 0
    done
    return 1
}

cleanup_inactive_managed_agents() {
    local agent_root="$1"
    local managed_marker="$2"
    local target_path target_file agent_name

    [[ -d "$agent_root" ]] || return 0
    for target_path in "$agent_root"/*; do
        [[ -f "$target_path" ]] || continue
        grep -q "$managed_marker" "$target_path" || continue
        target_file="$(basename "$target_path")"
        case "$target_file" in
            *.toml)
                agent_name="${target_file%.toml}"
                ;;
            *.md)
                agent_name="${target_file%.md}"
                ;;
            *)
                continue
                ;;
        esac
        if ! is_active_project_agent_name "$agent_name"; then
            rm -f "$target_path"
        fi
    done
}

render_agent_source_dir() {
    local agent_root="$1"
    local source_dir="$2"
    local source_label="$3"
    local kind_filter="$4"
    local override_dir="${5:-}"
    local managed_marker="Generated by agentic-researcher"
    local source_path agent_name kind description codex_reasoning_effort target_path

    [[ -d "$source_dir" ]] || return 0

    for source_path in "$source_dir"/*.md; do
        [[ -f "$source_path" ]] || continue
        agent_name="$(agent_name_for_source "$source_path")"
        if [[ -n "$override_dir" ]] && agent_name_exists_in_source_dir "$agent_name" "$override_dir"; then
            continue
        fi
        kind="$(agent_kind_for_source "$source_path")"
        if [[ "$kind" != "$kind_filter" ]]; then
            continue
        fi
        description="$(frontmatter_value "$source_path" "description")"
        codex_reasoning_effort="$(frontmatter_value "$source_path" "codex_reasoning_effort")"
        if [[ -z "$codex_reasoning_effort" ]]; then
            codex_reasoning_effort="$(frontmatter_value "$source_path" "model_reasoning_effort")"
        fi
        [[ -n "$description" ]] || description="$agent_name agent."

        if ! valid_agent_name "$agent_name"; then
            echo "Warning: Skipping $source_label agent with invalid name: $agent_name"
            continue
        fi

        target_path="$(cli_call_required agent_target_path "$agent_root" "$agent_name")"
        [[ -n "$target_path" ]] || continue

        if [[ -f "$target_path" ]] && ! grep -q "$managed_marker" "$target_path"; then
            echo "Warning: Skipping $source_label agent at $target_path (not managed by agentic-researcher)"
            continue
        fi

        render_agent_for_tool "$source_path" "$target_path" "$agent_name" "$description" "$codex_reasoning_effort"
    done
}

setup_project_agents() {
    local agent_root org_agent_dir=""
    local render_status=0
    agent_root="$(project_agent_root_for_tool)"
    [[ -n "$agent_root" ]] || return 0

    mkdir -p "$agent_root"

    if [[ -n "${AR_ORG_NOTES_REPO:-}" ]]; then
        org_agent_dir="$STATE_ROOT/repos/org-agentic-notes/agents"
    fi

    ACTIVE_PROJECT_AGENT_NAMES=()
    collect_active_project_agent_names "$SCRIPT_DIR/agents" "$org_agent_dir"
    collect_active_project_agent_names "$org_agent_dir" ""
    cleanup_inactive_managed_agents "$agent_root" "Generated by agentic-researcher"
    prepare_provider_sections

    if ! render_agent_source_dir "$agent_root" "$SCRIPT_DIR/agents" "built-in" "subagent" "$org_agent_dir"; then
        render_status=1
    fi

    if [[ -n "${AR_ORG_NOTES_REPO:-}" ]]; then
        if ! render_agent_source_dir "$agent_root" "$org_agent_dir" "org" "subagent"; then
            render_status=1
        fi
    fi

    cleanup_provider_sections
    return "$render_status"
}

append_skill_instruction_block() {
    local output_path="$1"
    local _skill_name="$2"
    local instruction_source="$3"

    [[ -f "$instruction_source" ]] || return 0

    {
        printf '\n'
        cat "$instruction_source"
    } >> "$output_path"
}

setup_skill_instruction_blocks() {
    local instruction_path="$WORKSPACE_DIR/$INSTRUCTION_TARGET"
    [[ -f "$instruction_path" ]] || return 0

    local temp_path="${instruction_path}.tmp"
    local source_path skill_name

    cp "$instruction_path" "$temp_path"

    for source_path in "$SCRIPT_DIR"/skills/*/INSTRUCTIONS.md; do
        [[ -f "$source_path" ]] || continue
        skill_name="$(basename "$(dirname "$source_path")")"
        append_skill_instruction_block "$temp_path" "$skill_name" "$source_path"
    done

    for skill_name in "${SELECTED_OPTIONAL_SKILLS[@]}"; do
        source_path="$SCRIPT_DIR/optional-skills/$skill_name/INSTRUCTIONS.md"
        append_skill_instruction_block "$temp_path" "$skill_name" "$source_path"
    done

    mv "$temp_path" "$instruction_path"
}

